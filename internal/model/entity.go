package model

import "time"

// TrackedEntity is a named entity the system watches for in incoming tweets.
// It can be added manually or promoted from NER results.
type TrackedEntity struct {
	ID         int64     `json:"id"`
	Name       string    `json:"name"`
	Type       string    `json:"type"`    // PER, LOC, ORG, MISC, or custom
	Aliases    []string  `json:"aliases"` // alternative spellings / transliterations
	Notes      string    `json:"notes"`
	Active     bool      `json:"active"`
	CreatedAt  time.Time `json:"created_at"`
	UpdatedAt  time.Time `json:"updated_at"`
	TrackCount int64     `json:"track_count,omitempty"`
}

// EntityTrack records a single match of a TrackedEntity against a tweet.
type EntityTrack struct {
	ID                int64     `json:"id"`
	EntityID          int64     `json:"entity_id"`
	EntityName        string    `json:"entity_name,omitempty"`
	TweetID           string    `json:"tweet_id"`
	MatchSource       string    `json:"match_source"` // "text" or "ner"
	Context           string    `json:"context"`
	Summary           string    `json:"summary,omitempty"` // generated by summarizer model
	TweetText         string     `json:"tweet_text,omitempty"`
	TweetAuthorHandle string     `json:"tweet_author_handle,omitempty"`
	TweetCreatedAt    *time.Time `json:"tweet_created_at,omitempty"`
	CreatedAt         time.Time  `json:"created_at"`
}

// NEREntity represents a single named entity extracted by a NER pipeline.
type NEREntity struct {
	Word  string  `json:"word"`
	Label string  `json:"label"`
	Score float32 `json:"score"`
}

// EntityCandidate is an entity discovered from tweet text that has not yet
// been reviewed. Candidates are upserted on every extraction run; once they
// cross confidence + frequency thresholds they are auto-promoted to TrackedEntity.
type EntityCandidate struct {
	ID               int64     `json:"id"`
	Word             string    `json:"word"`
	Type             string    `json:"type"`
	OccurrenceCount  int       `json:"occurrence_count"`
	AvgConfidence    float64   `json:"avg_confidence"`
	Sources          []string  `json:"sources"` // pipeline names that contributed
	Status           string    `json:"status"`  // pending | promoted | rejected
	PromotedEntityID *int64    `json:"promoted_entity_id,omitempty"`
	AutoPromoted     bool      `json:"auto_promoted"`
	FirstSeenAt      time.Time `json:"first_seen_at"`
	LastSeenAt       time.Time `json:"last_seen_at"`
}
